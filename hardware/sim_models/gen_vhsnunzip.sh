#!/usr/bin/env bash
# Convert the vhsnunzip decompressor (VHDL, parcore/vhsnunzip) to Verilog for Verilator with GHDL.
#
# Usage: hardware/sim_models/gen_vhsnunzip.sh [<parcore dir>]
#   writes vhsnunzip_quad.v next to this script; <parcore dir> defaults to ../../parcore.
#
# Needs ghdl with Verilog output (GHDL 5 or newer, for example from the YosysHQ OSS CAD Suite).
# VHDL-2008 with -frelaxed: the 93 mode cannot resolve the textio helpers of vhsnunzip_int_pkg.
# Takes the files the xsim project compiles (tb_user_vhdl.prj), without the .syn.vhd variants:
# those instantiate Xilinx primitives, the .sim.vhd variants are the behavioural versions.
# Run it again when parcore moves to a vhsnunzip with changes.
set -euo pipefail

HERE=$(realpath "$(dirname "$0")")
PARCORE=$(realpath "${1:-$HERE/../../parcore}")
SRC=$PARCORE/vhsnunzip/src/hdl
OUT=$HERE/vhsnunzip_quad.v

command -v ghdl > /dev/null || { echo "ghdl not found in PATH" >&2; exit 1; }

FILES=(
    vhsnunzip_utils_pkg.vhd
    vhsnunzip_int_pkg.vhd
    vhsnunzip_quad_pkg.vhd
    vhsnunzip_quad_bfifo.vhd
    vhsnunzip_quad.vhd
    vhsnunzip_quad_add48.sim.vhd
    vhsnunzip_quad_lram.sim.vhd
    vhsnunzip_quad_datapath.vhd
    vhsnunzip_quad_decoder.vhd
    vhsnunzip_quad_group.vhd
    vhsnunzip_quad_uram.vhd
    vhsnunzip_quad_lt_mem.vhd
)
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
{
    echo "// Generated by $(basename "$0") with $(ghdl --version | head -1)"
    echo "// from parcore $(git -C "$PARCORE" rev-parse --short HEAD) vhsnunzip/src/hdl: ${FILES[*]}"
    echo "// Do not edit. Verilator takes this file when vhsnunzip_quad is missing (sim/vl/build.sh, VL_MODELS)."
    echo '`timescale 1ns / 1ps'
    ghdl --synth --std=08 -fsynopsys -frelaxed --workdir="$WORK" --out=verilog "${FILES[@]/#/$SRC/}" -e vhsnunzip_quad
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "$OUT: $(wc -l < "$OUT") lines, $(grep -c '^module ' "$OUT") modules"
