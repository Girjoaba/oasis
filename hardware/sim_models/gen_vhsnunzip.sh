#!/usr/bin/env bash
# Convert the vhsnunzip decompressor (VHDL, parcore/vhsnunzip) to Verilog for Verilator with GHDL.
#
# Usage: hardware/sim_models/gen_vhsnunzip.sh [<parcore dir>]
#   writes vhsnunzip_quad.v next to this script; <parcore dir> defaults to ../../parcore.
#
# Needs ghdl with Verilog output (GHDL 5 or newer, for example from the YosysHQ OSS CAD Suite).
# GHDL finds the files and their order: it imports every .vhd of vhsnunzip/src/hdl except the
# .syn.vhd variants (those instantiate Xilinx primitives, the .sim.vhd variants are the behavioural
# versions), and `ghdl -m` writes the files vhsnunzip_quad needs, in order, to e~vhsnunzip_quad.lst.
# The link step of -m fails with the GHDL of the OSS CAD Suite on Ubuntu 22.04 (glibc too old) and
# --elab-order prints nothing there, so the list file is the result and the exit code of -m is not.
set -euo pipefail

HERE=$(realpath "$(dirname "$0")")
PARCORE=$(realpath "${1:-$HERE/../../parcore}")
SRC=$PARCORE/vhsnunzip/src/hdl
OUT=$HERE/vhsnunzip_quad.v
TOP=vhsnunzip_quad

command -v ghdl > /dev/null || { echo "ghdl not found in PATH" >&2; exit 1; }

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
OPTS=(--std=08 -fsynopsys -frelaxed --workdir="$WORK")
find "$SRC" -name "*.vhd" ! -name "*.syn.vhd" -print0 | xargs -0 ghdl -i "${OPTS[@]}"
# -m puts its objects into the current folder.
(cd "$WORK" && ghdl -m "${OPTS[@]}" "$TOP" > make.log 2>&1) || [ -f "$WORK/e~$TOP.lst" ] \
    || { grep -v warning "$WORK/make.log" | head -20 >&2; echo "ghdl -m found no order for $TOP" >&2; exit 1; }
mapfile -t FILES < <(grep "^$SRC/" "$WORK/e~$TOP.lst")
{
    echo "// Generated by $(basename "$0") with $(ghdl --version | head -1)"
    echo "// from parcore $(git -C "$PARCORE" rev-parse --short HEAD) vhsnunzip/src/hdl: ${FILES[*]#$SRC/}"
    echo "// Do not edit. Verilator takes this file when $TOP is missing (sim/vl/build.sh, VL_MODELS)."
    echo '`timescale 1ns / 1ps'
    ghdl --synth "${OPTS[@]}" --out=verilog "${FILES[@]}" -e "$TOP"
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "$OUT: $(wc -l < "$OUT") lines, $(grep -c '^module ' "$OUT") modules"
